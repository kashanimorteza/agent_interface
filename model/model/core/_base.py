"""Private Base: the strict Validation every Entity runs."""

from contextvars import ContextVar
from typing import Any, ClassVar, Final, LiteralString, Self, cast

from pydantic import ValidationError, ValidationInfo, field_validator
from pydantic_core import InitErrorDetails, PydanticCustomError
from sqlmodel import SQLModel
from sqlmodel.main import SQLModelConfig, SQLModelMetaclass

from model.core._storage import REGISTRY, physical_entity_name, physical_field_name
from model.core._types import TEXT_FORMS, annotation, conforms, decode_text
from model.core.declaration import (
    Declaration,
    FieldDeclaration,
    FieldType,
    ValueGeneration,
)

HIDDEN: Final = "[hidden sensitive value]"
"""Replaces the input of a Field carrying a Sensitivity Marker in validation messages."""

JSON_CONTEXT: Final = "json_object"
"""Validation context key marking values decoded from a JSON Object."""

_NOT_SUPPORTED: Final = (
    "Entities support only validated construction, assignment, to_json, and from_json"
)

_internal: ContextVar[bool] = ContextVar("_internal", default=False)


class _EntityMetaclass(SQLModelMetaclass):
    """Keeps each Entity's Declaration a read-only member of its type once it is defined."""

    def __init__(cls, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        type.__setattr__(cls, "_sealed", "declaration" in vars(cls))

    def __setattr__(cls, name: str, value: Any) -> None:
        if name == "declaration" and vars(cls).get("_sealed"):
            raise AttributeError(f"{cls.__name__}.declaration is read-only")
        super().__setattr__(name, value)

    def __delattr__(cls, name: str) -> None:
        if name == "declaration" and vars(cls).get("_sealed"):
            raise AttributeError(f"{cls.__name__}.declaration is read-only")
        super().__delattr__(name)


class Base(SQLModel, metaclass=_EntityMetaclass, registry=REGISTRY):
    """Validates every Entity strictly on construction and on assignment."""

    model_config = SQLModelConfig(
        strict=True,
        extra="forbid",
        validate_default=True,
        allow_inf_nan=False,
    )

    declaration: ClassVar[Declaration]

    __hash__ = None  # type: ignore[assignment]

    @classmethod
    def __pydantic_init_subclass__(cls, **kwargs: Any) -> None:
        super().__pydantic_init_subclass__(**kwargs)
        declaration = vars(cls).get("declaration")
        if declaration is None:
            return
        if not isinstance(declaration, Declaration):
            raise TypeError(f"{cls.__name__}.declaration must be a Declaration")
        physical = physical_entity_name(declaration.name)
        problems: list[str] = []
        if cls.__name__ != physical:
            problems.append(f"type name {cls.__name__!r} is not {physical!r}")
        if vars(cls).get("__tablename__") != physical:
            problems.append(f"table name is not {physical!r}")
        declared = [physical_field_name(field.name) for field in declaration.fields]
        if list(cls.model_fields) != declared:
            problems.append(f"Fields {list(cls.model_fields)} are not {declared}")
        else:
            for field in declaration.fields:
                optional = (
                    field.nullable
                    or field.value_generation is ValueGeneration.AUTO_INCREMENT
                )
                realized = annotation(field.type, optional=optional)
                if cls.model_fields[field.name].annotation != realized:
                    problems.append(
                        f"Field {field.name!r} is not realized as {field.type}"
                    )
        if problems:
            raise TypeError(
                f"{cls.__name__} does not match its Declaration: " + "; ".join(problems)
            )

    @classmethod
    def _field(cls, name: str) -> FieldDeclaration:
        return next(field for field in cls.declaration.fields if field.name == name)

    @field_validator("*", mode="before")
    @classmethod
    def _enforce_declaration(cls, value: Any, info: ValidationInfo) -> Any:
        field = cls._field(info.field_name or "")
        if (
            field.value_generation is ValueGeneration.AUTO_INCREMENT
            and value is not None
        ):
            raise PydanticCustomError(
                "generated_value",
                "Value is generated by storage and cannot be supplied",
            )
        if (info.context or {}).get(JSON_CONTEXT):
            if (
                field.type in TEXT_FORMS
                and value is not None
                and not conforms(field.type, value)
            ):
                decoded = decode_text(field.type, value) if type(value) is str else None
                if decoded is None:
                    raise PydanticCustomError(
                        "text_form",
                        "Input should be the text form of a {field_type}",
                        {"field_type": str(field.type)},
                    )
                return decoded
            if field.type is FieldType.FLOAT and type(value) is int:
                try:
                    return float(value)
                except OverflowError:
                    raise PydanticCustomError(
                        "finite_number", "Input should be a finite number"
                    ) from None
        elif field.type is FieldType.FLOAT and type(value) is int:
            raise PydanticCustomError("float_type", "Input should be a valid number")
        return value

    @classmethod
    def _hidden(cls, error: ValidationError) -> ValidationError:
        """Rebuild an error so that no marked Field's input appears in it."""
        declaration = vars(cls).get("declaration") or getattr(cls, "declaration", None)
        marked = (
            {
                field.name
                for field in declaration.fields
                if field.sensitivity is not None
            }
            if declaration is not None
            else set()
        )
        details: list[InitErrorDetails] = []
        for item in error.errors(include_url=False):
            location = item["loc"]
            value = item["input"]
            if location and location[0] in marked:
                value = HIDDEN
            elif isinstance(value, dict):
                value = {
                    key: HIDDEN if key in marked else entry
                    for key, entry in value.items()
                }
            details.append(
                InitErrorDetails(
                    type=PydanticCustomError(
                        cast(LiteralString, item["type"]),
                        cast(LiteralString, item["msg"]),
                    ),
                    loc=location,
                    input=value,
                )
            )
        return ValidationError.from_exception_data(error.title, details)

    @classmethod
    def _fail(cls, error: ValidationError) -> ValidationError:
        hidden = cls._hidden(error)
        hidden.__traceback__ = None
        return hidden

    @classmethod
    def model_validate(
        cls,
        obj: Any,
        *,
        strict: bool | None = None,
        from_attributes: bool | None = None,
        context: dict[str, Any] | None = None,
        update: dict[str, Any] | None = None,
    ) -> Self:
        """Validate a mapping with the same strict rules as direct construction."""
        if strict is False:
            raise TypeError("Entities are always validated strictly")
        failure: ValidationError | None = None
        token = _internal.set(True)
        try:
            validated = super().model_validate(
                obj,
                strict=True,
                from_attributes=from_attributes,
                context=context,
                update=update,
            )
        except ValidationError as error:
            failure = cls._fail(error)
        finally:
            _internal.reset(token)
        if failure is not None:
            raise failure
        return validated

    @classmethod
    def _validated(cls, data: dict[str, Any], *, json_object: bool = False) -> Self:
        return cls.model_validate(data, context={JSON_CONTEXT: json_object})

    @classmethod
    def model_construct(cls, *args: Any, **kwargs: Any) -> Self:
        """Unvalidated construction is not part of the Entity contract."""
        raise TypeError(_NOT_SUPPORTED)

    @classmethod
    def model_validate_json(cls, *args: Any, **kwargs: Any) -> Self:
        """JSON reconstruction goes through from_json only."""
        raise TypeError(_NOT_SUPPORTED)

    @classmethod
    def model_validate_strings(cls, *args: Any, **kwargs: Any) -> Self:
        """String reconstruction is not part of the Entity contract."""
        raise TypeError(_NOT_SUPPORTED)

    def model_copy(self, *args: Any, **kwargs: Any) -> Self:
        """Copying is not part of the Entity contract."""
        raise TypeError(_NOT_SUPPORTED)

    def copy(self, *args: Any, **kwargs: Any) -> Self:
        """Copying is not part of the Entity contract."""
        raise TypeError(_NOT_SUPPORTED)

    def __copy__(self) -> Self:
        raise TypeError(_NOT_SUPPORTED)

    def __deepcopy__(self, memo: dict[int, Any] | None = None) -> Self:
        raise TypeError(_NOT_SUPPORTED)

    def __delattr__(self, name: str) -> None:
        if name in type(self).model_fields:
            raise AttributeError(f"Field {name!r} cannot be removed")
        super().__delattr__(name)

    def __init__(self, **data: Any) -> None:
        if _internal.get():
            super().__init__(**data)
            return
        validated = type(self)._validated(data)
        token = _internal.set(True)
        try:
            super().__init__(
                **{name: validated.__dict__[name] for name in type(self).model_fields}
            )
        finally:
            _internal.reset(token)

    def __setattr__(self, name: str, value: Any) -> None:
        cls = type(self)
        if _internal.get() or name not in cls.model_fields:
            super().__setattr__(name, value)
            return
        field = cls._field(name)
        refusal: PydanticCustomError | None = None
        if field.value_generation is ValueGeneration.AUTO_INCREMENT:
            refusal = PydanticCustomError(
                "generated_value",
                "Value is generated by storage and cannot be supplied",
            )
        elif field.immutable:
            refusal = PydanticCustomError("frozen_field", "Field is immutable")
        if refusal is not None:
            raise cls._hidden(
                ValidationError.from_exception_data(
                    cls.__name__,
                    [InitErrorDetails(type=refusal, loc=(name,), input=value)],
                )
            )
        data = {
            key: getattr(self, key)
            for key in cls.model_fields
            if key != name
            and cls._field(key).value_generation is not ValueGeneration.AUTO_INCREMENT
        }
        data[name] = value
        validated = cls._validated(data)
        token = _internal.set(True)
        try:
            super().__setattr__(name, validated.__dict__[name])
        finally:
            _internal.reset(token)
